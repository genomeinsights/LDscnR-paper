## integer-position resolution once per table (character indexing rebuilds a
## 790k-name hash per call -- the "hash trap" 3SP_RESULTS.md §G/I7 flags)
prep <- function(dt, lab) {
  dt <- dt[n_loci >= 2L]
  flat <- unlist(dt$members, use.names = FALSE)
  idx  <- split(match(flat, names(pval)), rep.int(seq_len(nrow(dt)), lengths(dt$members)))
  P <- unname(pval); Q <- unname(pos); W <- unname(ldw[names(pval)])
  dt[, start := vapply(idx, function(j) min(Q[j]), 0)]
  dt[, end   := vapply(idx, function(j) max(Q[j]), 0)]
  dt[, span_kb := (end - start) / 1e3]
  dt[, p_minp  := vapply(idx, function(j) min(P[j]), 0)]
  dt[, p_simes := vapply(idx, function(j) simes(P[j]), 0)]
  set.seed(SEED)
  dt[, p_rand  := vapply(idx, function(j) P[if (length(j) == 1L) j else sample(j, 1L)], 0)]
  dt[, p_ldw   := vapply(idx, function(j) P[j[which.max(W[j])]], 0)]
  dt[, p_centr := unname(pval[rep_snp])]
  dt[, .idx := idx]
  say("[1] %s prepared: %s units with >=2 markers\n", lab, format(nrow(dt), big.mark=","))
  dt
}

## D1's diagnostic: where does each chooser's SNP sit in its own cluster's
## p-value ranking? (1 = best of n.) Computed only on the retained (post-c_min)
## units -- match() per row over 790k names is the hash trap again if done earlier.
add_ranks <- function(k) {
  P <- unname(pval); W <- unname(ldw[names(pval)])
  ri <- match(k$rep_snp, names(pval))
  k[, rk_ldw   := vapply(seq_len(.N), function(i) { j <- .idx[[i]]
                    sum(P[j] <= P[j[which.max(W[j])]]) }, 0L)]
  k[, rk_centr := vapply(seq_len(.N), function(i) { j <- .idx[[i]]
                    sum(P[j] <= P[ri[i]]) }, 0L)]
  k[]
}
U1 <- prep(S1, "Stage 1"); U2 <- prep(S2, "Stage 2")

## ---- 2. pick c_min per partition for ~TARGET units, apply the span cap ------
pick <- function(u) { sz <- vapply(CGRID, function(k) sum(u$n_loci >= k & u$span_kb <= SPAN_CAP), 0L)
                      CGRID[which.min(abs(sz - TARGET))] }
c1 <- pick(U1); c2 <- pick(U2)
K1 <- add_ranks(U1[n_loci >= c1 & span_kb <= SPAN_CAP])
K2 <- add_ranks(U2[n_loci >= c2 & span_kb <= SPAN_CAP])
say("\n[2] Stage 1: c_min = %d -> %d units ; Stage 2: c_min = %d -> %d units\n",
    c1, nrow(K1), c2, nrow(K2))

