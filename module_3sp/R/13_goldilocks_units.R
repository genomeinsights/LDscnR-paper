## ---- 4. detection, and the D1 rank diagnostic -------------------------------
UN <- c("minp","simes","emlg","rand","ldw","centr")
UN_LAB <- c(minp = "min-p (uses phenotype)", simes = "Simes", emlg = "eMLG consensus",
           rand = "random member", ldw = "highest ld\\_w", centr = "centrality")
summarise_partition <- function(k, lab) { n <- nrow(k); bonf <- ALPHA / n
  say("\n=== %s : %d units (c_min per partition) ; Bonferroni = %.2e ===\n", lab, n, bonf)
  tb <- rbindlist(lapply(UN, function(v) { p <- k[[paste0("p_", v)]]; p <- p[!is.na(p)]
    data.table(partition = lab, unit = v, uses_phenotype = v == "minp", n_with_p = length(p),
               min_p = signif(min(p), 3), sig_bonf = sum(p <= bonf),
               sig_bh = sum(p.adjust(p, "BH") <= ALPHA), median_p = signif(median(p), 3)) }))
  print(tb)
  say("  D1 diagnostic: median within-unit rank -- ld_w %.0f, centrality %.0f, of median n = %.0f\n",
      median(k$rk_ldw), median(k$rk_centr), median(k$n_loci))
  tb[, `:=`(bonferroni = bonf, median_rk_ldw = median(k$rk_ldw), median_rk_centr = median(k$rk_centr),
           median_n = median(k$n_loci))]
}
TAB1 <- summarise_partition(K1, "Stage 1")
TAB2 <- summarise_partition(K2, "Stage 2")
SUMMARY <- rbind(TAB1, TAB2)

## ---- 5. against the (substitute) truth set ----------------------------------
L <- fread(file.path(LDPP, "results_3sp", "3sp_cmin_loci.csv"))
score <- function(k, lab) { n <- nrow(k); bonf <- ALPHA / n
  k2 <- copy(k)[, chr_num := as.integer(gsub("Chr", "", Chr))]
  KK <- k2[, c("chr_num","start","end", paste0("p_", UN)), with = FALSE]; setkey(KK, chr_num, start, end)
  ov <- foverlaps(L[, .(chr_num, start, end, locus)], KK,
                  by.x = c("chr_num","start","end"), type = "any", nomatch = NA)
  r <- ov[, lapply(.SD, function(z) suppressWarnings(min(z, na.rm = TRUE))), by = locus,
          .SDcols = paste0("p_", UN)]
  r <- merge(L[, .(locus, lab2 = lab, ntot, KGlob, KPac)], r, by = "locus")
  cnt <- function(sub) vapply(UN, function(v) sum(is.finite(sub[[paste0("p_",v)]]) &
                                sub[[paste0("p_",v)]] <= bonf), 0L)
  rbindlist(list(
    data.table(partition = lab, set = "all loci", n = nrow(r),
               in_part = sum(is.finite(r$p_minp)), t(cnt(r))),
    data.table(partition = lab, set = "corroborated >=2", n = sum(r$ntot >= 2),
               in_part = sum(is.finite(r$p_minp) & r$ntot >= 2), t(cnt(r[ntot >= 2]))),
    data.table(partition = lab, set = "Kingman-supported", n = sum(r$KGlob | r$KPac),
               in_part = sum(is.finite(r$p_minp) & (r$KGlob | r$KPac)),
               t(cnt(r[KGlob | KPac])))))
}
TRUTHSET <- rbind(score(K1, "Stage 1"), score(K2, "Stage 2"))
say("\n[5] loci detected at Bonferroni, by partition and unit (PROXY truth set)\n")
print(TRUTHSET)

